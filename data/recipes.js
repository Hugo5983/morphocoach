export function recipeBadge(r) {
  if (r.temps <= 8)  return { l:`${r.temps} MIN`,   c:"#9DB0FF" };
  if (r.prot  >= 38) return { l:`${r.prot}G PROT.`, c:"#9DB0FF" };
  if (r.tags.includes("vegan"))              return { l:"VEGAN",        c:"#12B76A" };
  if (r.tags.includes("anti_inflammatoire")) return { l:"ANTI-INFLAM.", c:"#12B76A" };
  if (r.difficulte ==="Facile")             return { l:"FACILE",       c:"#12B76A" };
  return { l:r.difficulte.toUpperCase(), c:"#9DB0FF" };
}
